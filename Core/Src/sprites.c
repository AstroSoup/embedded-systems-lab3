void oled_DrawBitmap(uint8_t x, uint8_t y, BitmapDef bmp, OLED_COLOR color) {
	uint32_t i, j;
	uint32_t stride = (bmp.Width + 7) / 8;
	uint8_t b;

	if (OLED_WIDTH < ((uint32_t)x + bmp.Width) ||
			OLED_HEIGHT < ((uint32_t)y + bmp.Height)) {
		return;
	}

	for (i = 0; i < bmp.Height; i++) {
		for (j = 0; j < bmp.Width; j++) {
			b = bmp.data[i * stride + (j >> 3)];
			oled_DrawPixel(x + j, y + i, (b & (0x80 >> (j & 7))) ? color : (OLED_COLOR)!color);
		}
	}
}
const uint16_t Tetromino_Shapes[7][4] = {
	{ 0x0F00, 0x2222, 0x00F0, 0x4444 },
	{ 0x0660, 0x0660, 0x0660, 0x0660 },
	{ 0x4E00, 0x4640, 0x0E40, 0x4C40 },
	{ 0x6C00, 0x4620, 0x06C0, 0x8C40 },
	{ 0xC600, 0x2640, 0x0C60, 0x4C80 },
	{ 0x8E00, 0x6440, 0x0E20, 0x44C0 },
	{ 0x2E00, 0x4460, 0x0E80, 0xC440 }
};

void oled_DrawSprite(uint8_t x, uint8_t y, SpriteDef sprite, uint8_t index, OLED_COLOR color) {
	uint32_t i, j;
	uint16_t b;

	if (OLED_WIDTH < ((uint32_t)x + sprite.SpriteWidth) ||
			OLED_HEIGHT < ((uint32_t)y + sprite.SpriteHeight)) {
		return;
	}

	for (i = 0; i < sprite.SpriteHeight; i++) {
		b = sprite.data[index * sprite.SpriteHeight + i];
		for (j = 0; j < sprite.SpriteWidth; j++) {
			if ((b << j) & 0x8000) {
				oled_DrawPixel(x + j, y + i, color);
			} else {
				oled_DrawPixel(x + j, y + i, (OLED_COLOR)!color);
			}
		}
	}
}

void oled_DrawTetromino(uint8_t x, uint8_t y, SpriteDef sprite, TetrisPiece piece, uint8_t rotation) {
	uint16_t shape = Tetromino_Shapes[piece][rotation & 3];
	uint8_t row, col;

	for (row = 0; row < 4; row++) {
		for (col = 0; col < 4; col++) {
			if (shape & (0x8000 >> (row * 4 + col))) {
				oled_DrawSprite(x + col * sprite.SpriteWidth,
				                y + row * sprite.SpriteHeight,
				                sprite, (uint8_t)piece + 1, White);
			}
		}
	}
}
